// roles.js - Access Hierarchy and Role Definitions

export const ROLES = {
    SQUADRON_COMMANDER: 'squadron_commander',
    CADET_COMMANDER: 'cadet_commander',
    SUPPLY_OFFICER: 'supply_officer',
    CADET_SUPPLY_OFFICER: 'cadet_supply_officer',
    MEMBER: 'member'
};

export const PERMISSIONS = {
    VIEW_CATALOG: 'view_catalog',
    SUBMIT_REQUEST: 'submit_request',
    APPROVE_REQUESTS: 'approve_requests',
    CHECK_OUT_ITEMS: 'check_out_items',
    CHECK_IN_ITEMS: 'check_in_items',
    MANAGE_SUPPLY: 'manage_supply',
    VIEW_FINANCIAL_REPORTS: 'view_financial_reports',
    VIEW_MEMBER_DIRECTORY: 'view_member_directory',
    CALL_REMINDERS: 'call_reminders',
    MANAGE_USER_ROLES: 'manage_user_roles'
};

// Access Matrix mapping Roles to their Allowed Capabilities
const ROLE_PERMISSIONS = {
    [ROLES.SQUADRON_COMMANDER]: [
        PERMISSIONS.VIEW_CATALOG, PERMISSIONS.SUBMIT_REQUEST, PERMISSIONS.APPROVE_REQUESTS,
        PERMISSIONS.CHECK_OUT_ITEMS, PERMISSIONS.CHECK_IN_ITEMS, PERMISSIONS.MANAGE_SUPPLY,
        PERMISSIONS.VIEW_FINANCIAL_REPORTS, PERMISSIONS.VIEW_MEMBER_DIRECTORY,
        PERMISSIONS.CALL_REMINDERS, PERMISSIONS.MANAGE_USER_ROLES
    ],
    [ROLES.CADET_COMMANDER]: [
        PERMISSIONS.VIEW_CATALOG, PERMISSIONS.SUBMIT_REQUEST, PERMISSIONS.APPROVE_REQUESTS,
        PERMISSIONS.VIEW_FINANCIAL_REPORTS, PERMISSIONS.VIEW_MEMBER_DIRECTORY, PERMISSIONS.CALL_REMINDERS
    ],
    [ROLES.SUPPLY_OFFICER]: [
        PERMISSIONS.VIEW_CATALOG, PERMISSIONS.SUBMIT_REQUEST, PERMISSIONS.APPROVE_REQUESTS,
        PERMISSIONS.CHECK_OUT_ITEMS, PERMISSIONS.CHECK_IN_ITEMS, PERMISSIONS.MANAGE_SUPPLY,
        PERMISSIONS.VIEW_FINANCIAL_REPORTS, PERMISSIONS.VIEW_MEMBER_DIRECTORY, PERMISSIONS.CALL_REMINDERS
    ],
    [ROLES.CADET_SUPPLY_OFFICER]: [
        PERMISSIONS.VIEW_CATALOG, PERMISSIONS.SUBMIT_REQUEST, PERMISSIONS.CHECK_OUT_ITEMS,
        PERMISSIONS.CHECK_IN_ITEMS, PERMISSIONS.VIEW_MEMBER_DIRECTORY
    ],
    [ROLES.MEMBER]: [
        PERMISSIONS.VIEW_CATALOG, PERMISSIONS.SUBMIT_REQUEST
    ]
};

/**
 * Checks if a user has permission to perform a specific action
 */
export function hasPermission(userRole, permission) {
    const allowedPermissions = ROLE_PERMISSIONS[userRole] || ROLE_PERMISSIONS[ROLES.MEMBER];
    return allowedPermissions.includes(permission);
}